#!/usr/bin/env python3
"""Backfill the pookie school schema from the 2026-10-05 StudentVUE gradebook dump.

Reads ~/workspace/dawson-grades/studentvue-gradebook-2026-10-05.json and
upserts into the live pookie project:
  classes, grades (term GP2), grade_snapshots (+category_averages),
  assignments (+assignment_type), school_sync_health + school_sync_runs.

Idempotent: every write is an upsert on a natural unique key
(classes: child+slug; grades: child+class+term; assignments: child+class+source_id;
health: child+source+machine). Safe to re-run.

Usage:
  python3 backfill_school_066.py            # write SQL + apply via mgmt API
  python3 backfill_school_066.py --sql-only # just write telemetry/backfill_066.sql

Apply path: POSTs the whole script to the Supabase management /database/query
endpoint (same path E4 used for migrations 066/067). For a REST/service_role
path, hand backfill_066.sql to the coordinator.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

JSON_PATH = Path.home() / "workspace/dawson-grades/studentvue-gradebook-2026-10-05.json"
OUT_SQL = Path(__file__).resolve().parent / "backfill_066.sql"
SBMGMT = Path("/tmp/sbmgmt-pookie.py")  # E4's mgmt-API shim (pookie project)

DAWSON = {"first_name": "Dawson", "last_name": "Kamal"}
TERM = "GP2"
SYNCED_AT = "2026-10-05T12:00:00+00"

CATEGORY_TO_TYPE = {
    "classwork": "classwork", "classwk/hw": "classwork", "class activity": "classwork",
    "homework/daily work": "homework", "homework": "homework",
    "quiz": "quiz", "quizzes": "quiz",
    "test": "test", "tests": "test", "assessment": "test",
    "project": "project", "projects": "project",
    "lab": "lab", "labs": "lab",
    "final": "final",
}

PALETTE = ["#34d399", "#2dd4bf", "#4ade80", "#a3e635", "#22d3ee", "#10b981"]


def lit(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "TRUE" if v else "FALSE"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def slugify(name: str) -> str:
    s = name.lower()
    s = re.sub(r"[^a-z0-9]+", "-", s).strip("-")
    return s


def canonical(name: str) -> tuple[str, str]:
    """(name, display_name): strip trailing ' A' (semester tag) and leading 'H ' (honors)."""
    display = re.sub(r"\s+A$", "", name).strip()
    base = re.sub(r"^H\s+", "", display).strip()
    return base, display


def parse_score(raw: str):
    """-> (earned, possible, status)."""
    s = (raw or "").strip()
    if not s:
        return None, None, "upcoming"
    if s.lower() == "upcoming":
        return None, None, "upcoming"
    m = re.match(r"^(\d+(?:\.\d+)?)\s+MISSING$", s, re.I)
    if m:
        return float(m.group(1)), None, "missing"
    m = re.match(r"^(\d+(?:\.\d+)?)/(\d+(?:\.\d+)?)$", s)
    if m:
        return float(m.group(1)), float(m.group(2)), "graded"
    m = re.match(r"^(\d+(?:\.\d+)?)$", s)
    if m:
        return float(m.group(1)), None, "graded"
    return None, None, "upcoming"


def parse_md(raw: str):
    m = re.match(r"^([A-Za-z]{3})\s+(\d{1,2})$", (raw or "").strip())
    if not m:
        return None
    months = {"Jan": 1, "Feb": 2, "Mar": 3, "Apr": 4, "May": 5, "Jun": 6,
              "Jul": 7, "Aug": 8, "Sep": 9, "Oct": 10, "Nov": 11, "Dec": 12}
    mon = months.get(m.group(1).title())
    if not mon:
        return None
    return f"2026-{mon:02d}-{int(m.group(2)):02d}"


def parse_us(raw: str):
    m = re.match(r"^(\d{1,2})/(\d{1,2})/(\d{4})$", (raw or "").strip())
    if not m:
        return None
    return f"{int(m.group(3)):04d}-{int(m.group(1)):02d}-{int(m.group(2)):02d}"


def main() -> int:
    dump = json.loads(JSON_PATH.read_text())
    stmts: list[str] = []
    counts = {"classes": 0, "grades": 0, "grade_snapshots": 0, "assignments": 0}

    stmts.append("-- Backfill 066: StudentVUE gradebook 2026-10-05 -> pookie school schema")
    stmts.append("-- Generated by telemetry/backfill_school_066.py. Idempotent upserts.")

    for i, c in enumerate(dump["classes"]):
        name, display = canonical(c["name"])
        slug = slugify(name)
        cats = c.get("categories")
        cats = cats if isinstance(cats, dict) else {}  # Lit/Geometry: weights not captured in this sweep
        weights = {k: v.get("weight") for k, v in cats.items()}
        cat_avgs = {k: {"avg": v.get("avg"), "weight": v.get("weight")}
                    for k, v in cats.items()}

        stmts.append(f"""
INSERT INTO public.classes
  (child_id, name, display_name, class_slug, period, teacher_name, room,
   display_order, grade_weights, color, active)
VALUES (
  (SELECT id FROM public.children
    WHERE first_name = {lit(DAWSON['first_name'])} AND last_name = {lit(DAWSON['last_name'])}),
  {lit(name)}, {lit(display)}, {lit(slug)}, {lit(str(c.get('period')))},
  {lit(c.get('teacher'))}, {lit(c.get('room'))}, {i + 1},
  {lit(json.dumps(weights))}::jsonb, {lit(PALETTE[i % len(PALETTE)])}, TRUE
)
ON CONFLICT (child_id, class_slug) DO UPDATE SET
  name = EXCLUDED.name, display_name = EXCLUDED.display_name,
  period = EXCLUDED.period, teacher_name = EXCLUDED.teacher_name,
  room = EXCLUDED.room, display_order = EXCLUDED.display_order,
  grade_weights = EXCLUDED.grade_weights, color = EXCLUDED.color;""".strip())
        counts["classes"] += 1

        grade = c.get("grade")
        stmts.append(f"""
INSERT INTO public.grades (child_id, class_id, term, numeric, source, synced_at)
VALUES (
  (SELECT id FROM public.children
    WHERE first_name = {lit(DAWSON['first_name'])} AND last_name = {lit(DAWSON['last_name'])}),
  (SELECT id FROM public.classes WHERE class_slug = {lit(slug)}
    AND child_id = (SELECT id FROM public.children
      WHERE first_name = {lit(DAWSON['first_name'])} AND last_name = {lit(DAWSON['last_name'])})),
  {lit(TERM)}, {lit(grade)}, 'studentvue', {lit(SYNCED_AT)}::timestamptz
)
ON CONFLICT (child_id, class_id, term) DO UPDATE SET
  numeric = EXCLUDED.numeric, source = EXCLUDED.source,
  synced_at = EXCLUDED.synced_at;""".strip())
        counts["grades"] += 1

        stmts.append(f"""
INSERT INTO public.grade_snapshots
  (child_id, class_id, term, numeric, category_averages, taken_at)
VALUES (
  (SELECT id FROM public.children
    WHERE first_name = {lit(DAWSON['first_name'])} AND last_name = {lit(DAWSON['last_name'])}),
  (SELECT id FROM public.classes WHERE class_slug = {lit(slug)}
    AND child_id = (SELECT id FROM public.children
      WHERE first_name = {lit(DAWSON['first_name'])} AND last_name = {lit(DAWSON['last_name'])})),
  {lit(TERM)}, {lit(grade)}, {lit(json.dumps(cat_avgs))}::jsonb,
  {lit(SYNCED_AT)}::timestamptz
);""".strip())
        counts["grade_snapshots"] += 1

        assigns = c.get("assignments")
        if not isinstance(assigns, list):
            continue  # e.g. Lit: "not individually captured" note string
        for j, a in enumerate(assigns):
            if not isinstance(a, dict):
                continue
            earned, possible, status = parse_score(a.get("score"))
            atype = CATEGORY_TO_TYPE.get((a.get("category") or "").strip().lower(), "other")
            due = parse_md(a.get("date"))
            sid = f"gradebook-20261005:{slug}:{j}"
            stmts.append(f"""
INSERT INTO public.assignments
  (child_id, class_id, source_id, title, category, assignment_type,
   due_date, status, points_earned, points_possible, synced_at)
VALUES (
  (SELECT id FROM public.children
    WHERE first_name = {lit(DAWSON['first_name'])} AND last_name = {lit(DAWSON['last_name'])}),
  (SELECT id FROM public.classes WHERE class_slug = {lit(slug)}
    AND child_id = (SELECT id FROM public.children
      WHERE first_name = {lit(DAWSON['first_name'])} AND last_name = {lit(DAWSON['last_name'])})),
  {lit(sid)}, {lit(a.get('title'))}, {lit(a.get('category'))}, {lit(atype)},
  {(lit(due + 'T00:00:00+00') + '::timestamptz') if due else 'NULL'},
  {lit(status)}, {lit(earned)}, {lit(possible)}, {lit(SYNCED_AT)}::timestamptz
)
ON CONFLICT (child_id, class_id, source_id) DO UPDATE SET
  title = EXCLUDED.title, category = EXCLUDED.category,
  assignment_type = EXCLUDED.assignment_type, due_date = EXCLUDED.due_date,
  status = EXCLUDED.status, points_earned = EXCLUDED.points_earned,
  points_possible = EXCLUDED.points_possible, synced_at = EXCLUDED.synced_at;""".strip())
            counts["assignments"] += 1

    # upcoming_assignments -> match class by display_name
    for k, u in enumerate(dump.get("upcoming_assignments") or []):
        base, display = canonical(u.get("class", ""))
        due = parse_us(u.get("due"))
        stmts.append(f"""
INSERT INTO public.assignments
  (child_id, class_id, source_id, title, due_date, status, synced_at)
VALUES (
  (SELECT id FROM public.children
    WHERE first_name = {lit(DAWSON['first_name'])} AND last_name = {lit(DAWSON['last_name'])}),
  (SELECT id FROM public.classes WHERE display_name = {lit(display)}
    AND child_id = (SELECT id FROM public.children
      WHERE first_name = {lit(DAWSON['first_name'])} AND last_name = {lit(DAWSON['last_name'])})),
  {lit(f'gradebook-20261005:upcoming:{k}')}, {lit(u.get('title'))},
  {(lit(due + 'T00:00:00+00') + '::timestamptz') if due else 'NULL'},
  'upcoming', {lit(SYNCED_AT)}::timestamptz
)
ON CONFLICT (child_id, class_id, source_id) DO UPDATE SET
  title = EXCLUDED.title, due_date = EXCLUDED.due_date,
  status = EXCLUDED.status, synced_at = EXCLUDED.synced_at;""".strip())
        counts["assignments"] += 1

    total = sum(counts.values())
    # Health row: honest 'stale' — the dump is 7 days old (> 26h freshness window).
    stmts.append(f"""
INSERT INTO public.school_sync_health
  (child_id, source_name, machine, cadence, expected_freshness,
   last_run_started, last_run_finished, last_success_at,
   rows_pulled, rows_by_table, error_text, consecutive_errors,
   next_scheduled_run, data_freshness_status)
VALUES (
  (SELECT id FROM public.children
    WHERE first_name = {lit(DAWSON['first_name'])} AND last_name = {lit(DAWSON['last_name'])}),
  'studentvue', 'laptop', 'daily', '26 hours',
  {lit(SYNCED_AT)}::timestamptz, {lit(SYNCED_AT)}::timestamptz, {lit(SYNCED_AT)}::timestamptz,
  {total}, {lit(json.dumps(counts))}::jsonb, NULL, 0, NULL, 'stale'
)
ON CONFLICT (child_id, source_name, machine) DO UPDATE SET
  last_run_started = EXCLUDED.last_run_started,
  last_run_finished = EXCLUDED.last_run_finished,
  last_success_at = EXCLUDED.last_success_at,
  rows_pulled = EXCLUDED.rows_pulled, rows_by_table = EXCLUDED.rows_by_table,
  error_text = NULL, consecutive_errors = 0,
  data_freshness_status = EXCLUDED.data_freshness_status;""".strip())

    stmts.append(f"""
INSERT INTO public.school_sync_runs
  (child_id, source_name, machine, started_at, finished_at,
   rows_pulled, rows_by_table, success)
VALUES (
  (SELECT id FROM public.children
    WHERE first_name = {lit(DAWSON['first_name'])} AND last_name = {lit(DAWSON['last_name'])}),
  'studentvue', 'laptop',
  {lit(SYNCED_AT)}::timestamptz, {lit(SYNCED_AT)}::timestamptz,
  {total}, {lit(json.dumps(counts))}::jsonb, TRUE
);""".strip())

    sql = "\n\n".join(s if s.endswith(";") else s + ";" for s in stmts) + "\n"
    OUT_SQL.write_text(sql)
    print(f"wrote {OUT_SQL} ({len(stmts)} statements, counts={counts})")

    if "--sql-only" in sys.argv:
        return 0
    if not SBMGMT.exists():
        print("mgmt shim missing; SQL written but not applied", file=sys.stderr)
        return 2
    r = subprocess.run(
        [sys.executable, str(SBMGMT), "query", "@" + str(OUT_SQL)],
        capture_output=True, text=True, timeout=300)
    print(r.stdout[-1500:])
    if r.returncode != 0:
        print(r.stderr[-1500:], file=sys.stderr)
    return r.returncode


if __name__ == "__main__":
    raise SystemExit(main())
